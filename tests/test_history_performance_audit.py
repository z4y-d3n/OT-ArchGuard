def test_external_input_alias_cannot_modify_a_completed_private_validation() -> None:
    state, ids = full_state()
    expected = copy.deepcopy(state["analyses"][ids["analysis"]])
    context = _ValidationContext(state)
    context.validate()
    state["attachments"][ids["model"]]["payload"]["revision"] = "Changed outside owned context"
    with pytest.raises(ModelError):
        lifecycle.validate_state(state)
    assert (
        context.build_revision(
            ids["snapshot"], {k: ids[k] for k in ("model", "mapping", "comparison")}
        )
        == expected
    )


def test_mutating_returned_builder_values_does_not_poison_operation_reuse() -> None:
    state, ids = full_state()
    context = _ValidationContext(state)
    context.validate()
    first = context.build_attachment("model", plant_model(), ids["snapshot"])
    first["payload"]["schema_version"] = True
    second = context.build_attachment("model", plant_model(), ids["snapshot"])
    assert second == state["attachments"][ids["model"]]
    first_revision = context.build_revision(ids["snapshot"], {"model": ids["model"]})
    expected = copy.deepcopy(first_revision)
    first_revision["producer_semantics"]["analysis_options"]["require_complete_scan"] = True
    first_revision["components"]["model"]["sha256"] = "f" * 64
    assert context.build_revision(ids["snapshot"], {"model": ids["model"]}) == expected



def test_replay_is_not_skipped_in_a_later_independent_operation(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    workspace, _, _ = stored(tmp_path)
    original = compare_capture
    replays: list[tuple[str, str]] = []

    def replay(*args: Any, **kwargs: Any) -> dict[str, Any]:
        replays.append((args[0]["observations_sha256"], args[1].sha256))
        return original(*args, **kwargs)

    monkeypatch.setattr(validation, "compare_capture", replay)
    assert lifecycle.verify_lifecycle(workspace)["analyses"] == 1
    assert lifecycle.verify_lifecycle(workspace)["analyses"] == 1
    assert len(replays) == 2 and replays[0] == replays[1]


def test_modified_same_size_mtime_file_is_not_trusted_after_previous_success(
    tmp_path: Path,
) -> None:
    workspace, _, ids = stored(tmp_path)
    lifecycle.verify_lifecycle(workspace)
    target = workspace / "attachments" / (ids["comparison"] + ".json")
    before = target.stat()
    value = json.loads(target.read_bytes())
    value["observations_sha256"] = "f" * 64
    changed = serialize(value)
    assert len(changed) == before.st_size
    target.write_bytes(changed)
    os.utime(target, ns=(before.st_atime_ns, before.st_mtime_ns))
    with pytest.raises(ModelError) as error:
        lifecycle.verify_lifecycle(workspace)
    assert error.value.diagnostics[0].code == "EVIDENCE_INTEGRITY"



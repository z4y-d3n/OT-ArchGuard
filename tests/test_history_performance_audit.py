def seal(kind: str, value: dict[str, Any]) -> dict[str, Any]:
    body = {k: v for k, v in value.items() if k != kind + "_id"}
    raw = json.dumps(
        {"domain": "otarchguard." + kind, "value": body},
        sort_keys=True,
        ensure_ascii=True,
        separators=(",", ":"),
    ).encode("ascii")
    return {**body, kind + "_id": kind + "-" + hashlib.sha256(raw).hexdigest()}


def full_state() -> tuple[dict[str, Any], dict[str, str]]:
    snapshot = build_snapshot(fixture("observations"), "Entirely fictional audit collection")
    model = build_attachment("model", plant_model(), snapshot)
    mapping = build_attachment("mapping", fixture("mapping"), snapshot, {"model": model})
    comparison = build_attachment(
        "comparison", fixture("comparison"), snapshot, {"model": model, "mapping": mapping}
    )
    components = {"model": model, "mapping": mapping, "comparison": comparison}
    analysis = build_revision(snapshot, components)
    state = {
        "snapshots": {snapshot["snapshot_id"]: snapshot},
        "attachments": {v["attachment_id"]: v for v in components.values()},
        "analyses": {analysis["analysis_id"]: analysis},
        "baselines": {},
        "reviews": {},
    }
    ids = {"snapshot": snapshot["snapshot_id"], "analysis": analysis["analysis_id"]}
    ids.update({k: v["attachment_id"] for k, v in components.items()})
    return state, ids


def stored(tmp_path: Path) -> tuple[Path, dict[str, Any], dict[str, str]]:
    state, ids = full_state()
    workspace = tmp_path / "fictional-history"
    history.initialize_history(workspace)
    for kind, values in state.items():
        for identity, value in values.items():
            (workspace / kind / (identity + ".json")).write_bytes(serialize(value))
    return workspace, state, ids



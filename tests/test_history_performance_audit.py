def test_new_revision_remains_unapproved_and_revocation_is_freshly_resolved(tmp_path: Path) -> None:
    workspace, state, ids = stored(tmp_path)
    scope_path = tmp_path / "scope.json"
    scope_path.write_bytes(serialize(audit_scope()))
    first = lifecycle.propose_baseline(workspace, scope_path, [ids["analysis"]])["baseline"]
    approved = lifecycle.record_review(
        workspace,
        first["baseline_id"],
        "approve",
        "Fictional auditor",
        "Synthetic initial reference",
    )["review"]
    semantics = build_semantics(state["snapshots"][ids["snapshot"]], require_complete_scan=True)
    semantics_path = tmp_path / "semantics.json"
    semantics_path.write_bytes(serialize(semantics))
    next_revision = lifecycle.create_revision(workspace, ids["snapshot"], semantics=semantics_path)[
        "analysis"
    ]
    second = lifecycle.propose_baseline(workspace, scope_path, [next_revision["analysis_id"]])[
        "baseline"
    ]
    assert second["status"] == "PROPOSED"
    assert (
        lifecycle.show_object(workspace, "baselines", first["baseline_id"])["status"] == "APPROVED"
    )
    revoked = lifecycle.record_review(
        workspace,
        first["baseline_id"],
        "revoke",
        "Fictional auditor",
        "Synthetic withdrawal",
        approved["review_id"],
    )
    assert revoked["baseline_status"] == "REVOKED"
    statuses = {
        b["baseline_id"]: b["status"] for b in lifecycle.list_baselines(workspace)["baselines"]
    }
    assert statuses == {first["baseline_id"]: "REVOKED", second["baseline_id"]: "PROPOSED"}


def test_conflicting_successor_cannot_escape_private_review_builder_before_publication(
    tmp_path: Path,
) -> None:
    workspace, state, ids = stored(tmp_path)
    scope = audit_scope()
    first = build_baseline("evidence", [ids["analysis"]], scope, state)
    state["baselines"][first["baseline_id"]] = first
    first_review = build_review(
        first["baseline_id"], "approve", "Fictional auditor", "First assertion", state
    )
    state["reviews"][first_review["review_id"]] = first_review
    for kind in ("baselines", "reviews"):
        for identity, value in state[kind].items():
            (workspace / kind / (identity + ".json")).write_bytes(serialize(value))
    before = set((workspace / "reviews").iterdir())
    with pytest.raises(ModelError):
        lifecycle.record_review(
            workspace,
            first["baseline_id"],
            "approve",
            "Another fictional auditor",
            "Contradictory assertion",
        )
    assert set((workspace / "reviews").iterdir()) == before
    assert lifecycle.verify_lifecycle(workspace)["approved_baselines"] == 1


def test_mutating_a_returned_public_state_does_not_create_later_approval(tmp_path: Path) -> None:
    workspace, _, ids = stored(tmp_path)
    returned = lifecycle.load_state(workspace)
    returned["attachments"][ids["model"]]["payload"]["revision"] = "External mutation"
    returned["reviews"]["review-" + "f" * 64] = {"decision": "approve"}
    assert lifecycle.verify_lifecycle(workspace)["reviews"] == 0
    assert (
        lifecycle.load_state(workspace)["attachments"][ids["model"]]["payload"]["revision"]
        != "External mutation"
    )
